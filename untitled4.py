import csv
import os
import re
from datetime import datetime

ARCHIVO = "expedientes.csv"
expedientes = []


# Cargar los expedientes guardados
def cargar_expedientes():
    if os.path.exists(ARCHIVO):
        with open(ARCHIVO, "r", newline="", encoding="utf-8") as archivo:
            lector = csv.DictReader(archivo)
            return list(lector)
    return []


# Guardar los expedientes en un archivo CSV
def guardar_expedientes():
    campos = ["codigo", "dni_ruc", "nombre", "tipo",
              "asunto", "correo", "fecha"]

    with open(ARCHIVO, "w", newline="", encoding="utf-8") as archivo:
        escritor = csv.DictWriter(archivo, fieldnames=campos)
        escritor.writeheader()
        escritor.writerows(expedientes)


# Validar los datos ingresados
def validar_entradas(dni_ruc, nombre, tipo, asunto, correo):
    if not all([dni_ruc, nombre, tipo, asunto, correo]):
        return False, "Todos los campos son obligatorios."

    if not (dni_ruc.isdigit() and len(dni_ruc) in [8, 11]):
        return False, "El DNI debe tener 8 dígitos o el RUC 11."

    if not re.match(r"^[^@\s]+@[^@\s]+\.[^@\s]+$", correo):
        return False, "El correo electrónico no es válido."

    return True, "Datos válidos."


# Generar un código correlativo
def generar_codigo():
    numero = len(expedientes) + 1
    return f"EXP-{datetime.now().year}-{numero:03d}"


# Registrar un nuevo expediente
def registrar_expediente(dni_ruc, nombre, tipo, asunto, correo):
    valido, mensaje = validar_entradas(
        dni_ruc, nombre, tipo, asunto, correo
    )

    if not valido:
        print(mensaje)
        return

    expediente = {
        "codigo": generar_codigo(),
        "dni_ruc": dni_ruc,
        "nombre": nombre,
        "tipo": tipo,
        "asunto": asunto,
        "correo": correo,
        "fecha": datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    }

    expedientes.append(expediente)
    guardar_expedientes()
    print("Expediente registrado correctamente.")
    print("Código generado:", expediente["codigo"])


# Buscar un expediente por su código
def buscar_por_codigo(codigo):
    for expediente in expedientes:
        if expediente["codigo"].lower() == codigo.lower():
            return expediente
    return None


# Mostrar los datos de un expediente
def mostrar_expediente(expediente):
    if expediente:
        for campo, valor in expediente.items():
            print(f"{campo}: {valor}")
    else:
        print("No se encontró el expediente.")


# Ordenar expedientes por código o fecha
def ordenar_expedientes(criterio="codigo"):
    if criterio in ["codigo", "fecha"]:
        return sorted(expedientes, key=lambda e: e[criterio])
    print("Criterio no válido.")
    return expedientes


# Mostrar el menú principal
def mostrar_menu():
    print("\n=== MESA DE PARTES DIGITAL ===")
    print("1. Registrar expediente")
    print("2. Buscar expediente")
    print("3. Ordenar expedientes")
    print("4. Mostrar todos los expedientes")
    print("5. Salir")


# Ejecutar el sistema
def main():
    global expedientes
    expedientes = cargar_expedientes()

    while True:
        mostrar_menu()
        opcion = input("Seleccione una opción: ")

        if opcion == "1":
            dni = input("DNI o RUC: ")
            nombre = input("Nombre completo: ")
            tipo = input("Tipo de trámite: ")
            asunto = input("Asunto: ")
            correo = input("Correo electrónico: ")
            registrar_expediente(dni, nombre, tipo, asunto, correo)

        elif opcion == "2":
            codigo = input("Código del expediente: ")
            mostrar_expediente(buscar_por_codigo(codigo))

        elif opcion == "3":
            criterio = input("Ordenar por código o fecha: ").lower()
            for expediente in ordenar_expedientes(criterio):
                mostrar_expediente(expediente)
                print("-" * 30)

        elif opcion == "4":
            for expediente in expedientes:
                mostrar_expediente(expediente)
                print("-" * 30)

        elif opcion == "5":
            print("Saliendo del sistema.")
            break

        else:
            print("Opción no válida. Intente nuevamente.")


# Iniciar el programa
main()